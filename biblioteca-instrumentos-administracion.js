export function aplicarGuiasAdministracion(
  instrumentos
) {

  instrumentos.forEach(
    instrumento => {

      const guia =
        guiasAdministracionInstrumentos[
          instrumento.id
        ];


      if (
        !guia
      ) {

        return;

      }


      Object.assign(
        instrumento,
        guia
      );

    }
  );


  return instrumentos;

}